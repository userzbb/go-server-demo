#!/bin/bash
# CI 集成测试脚本
# 在 CI 流水线中运行，验证完整的服务功能

set -e

echo "========================================="
echo "  运行 CI 集成测试"
echo "========================================="

# 1. 启动数据库
echo "[1/4] 启动数据库..."
make db-up
sleep 5

# 2. 初始化表结构
echo "[2/4] 初始化数据库..."
make db-init

# 3. 测试数据库连接
echo "[3/4] 测试数据库连接..."
make db-test

# 4. 运行单元测试
echo "[4/4] 运行单元测试..."
make test

echo "========================================="
echo "  ✅ CI 集成测试全部通过！"
echo "========================================="
